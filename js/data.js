  function workout(pid, idx) {
    const p = PROGRAMS.find(x => x.id === pid) || PROGRAMS[0];
    const t = p.templates[idx % p.templates.length];
    const level = Math.floor(idx / p.templates.length);        // какой круг шаблонов
    const k = 1 + 0.12 * level;
    const rounds = 2 + (level >= 2 ? 1 : 0);
    const items = t.items.map(([id, amount]) => {
      const ex = EXERCISES[id];
      const v = Math.round(amount * k / (ex.type === 'time' ? 5 : 1)) * (ex.type === 'time' ? 5 : 1);
      return { id, amount: v };
    });
    return { pid: p.id, idx, program: p.title, title: `День ${idx + 1} · ${t.title}`, short: t.title, rounds, rest: p.rest, items };
  }

  // секунды на одно упражнение (повторение ≈ 3 с, «на каждую сторону» — вдвое дольше)
  function exSeconds(item) {
    const ex = EXERCISES[item.id];
    const s = ex.type === 'time' ? item.amount : item.amount * 3;
    return ex.sides ? s * 2 : s;
  }
  function plan(w, weightKg) {
    let sec = 0, kcal = 0;
    for (let r = 0; r < w.rounds; r++) {
      w.items.forEach(it => {
        const s = exSeconds(it);
        sec += s + w.rest;
        kcal += EXERCISES[it.id].met * 3.5 * (weightKg || 70) / 200 * (s / 60);
      });
      sec += 40; // пауза между раундами
    }
    sec += 120; // разминка/заминка
    return { min: Math.max(5, Math.round(sec / 60)), kcal: Math.round(kcal + (weightKg || 70) * 0.04 * 2) };
  }

